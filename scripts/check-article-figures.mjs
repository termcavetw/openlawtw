import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {prepareArticleFigures} from './prepare-article-figures.mjs';
import {articleFiguresHTML} from '../lib/article-figures.ts';
import {lawPrintHTML} from '../lib/law-print.ts';
const raw=JSON.parse(fs.readFileSync('public/data/laws.json'));
const fixtures=await prepareArticleFigures(process.cwd(),raw);
const manifest=JSON.parse(fs.readFileSync('public/data/manifest.json'));
const f=manifest.laws.D0070115,law=JSON.parse(fs.readFileSync('public'+f.url));
const article=law.articles.find(a=>a.no==='第 116-2 條');
assert.deepEqual(article.figures,fixtures.D0070115['第 116-2 條']);
assert.equal(article.text,'前條安全維護裝置應依下表規定設置：');
const figure=article.figures[0];
const bytes=data=>Buffer.from(data.split(',')[1],'base64');
const sha=data=>createHash('sha256').update(data).digest('hex');
assert.equal(sha(bytes(figure.pdf)),figure.sha256);
assert.equal(sha(bytes(figure.images[0].src)),figure.images[0].sha256);
assert.ok(manifest.packs.find(p=>p.id==='中央').files.some(p=>p.url===f.url),'Offline pack includes source PDF and table image with the law');
const printed=lawPrintHTML(law,{kind:'article',article:article.no});
assert.ok(printed.includes(figure.images[0].src),'Print embeds original image without network');
assert.ok(printed.includes('原檔第 2 頁'));
const staticPage=fs.readFileSync('dist/laws/D0070115.html','utf8');
assert.ok(staticPage.includes(figure.images[0].src),'No-JavaScript page includes table');
assert.ok(staticPage.includes(figure.pdf),'No-JavaScript page retains downloadable original');
const invalid={...article,figures:[{...figure,source:'javascript:alert(1)',pdf:'data:text/html,x',images:[{...figure.images[0],src:'x" onerror="alert(1)'}]}]};
assert.equal(articleFiguresHTML(invalid),'');
const changed=structuredClone(raw);changed.D0070115.attachments=[];
await assert.rejects(()=>prepareArticleFigures(process.cwd(),changed),/no longer matches/);
console.log('Official article image checks passed: source bytes, print/static display, offline pack, safe markup and changed-source rejection.');
